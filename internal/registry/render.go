package registry

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Markers delimit arc-generated blocks in markdown files. Text outside them
// is never touched.
const (
	BeginMarker = "<!-- arc:begin -->"
	EndMarker   = "<!-- arc:end -->"
)

// ArchitectureFile holds the rendered registry block.
const ArchitectureFile = "ARCHITECTURE.md"

// SnippetFiles get the agent instruction snippet. AGENTS.md is created if
// missing; the others only when present.
var SnippetFiles = []string{"AGENTS.md", "CLAUDE.md"}

const architectureHeader = `# Architecture

Describe the system's design here. The section between the arc markers is
generated from ` + "`" + Path + "`" + ` by ` + "`arc render`" + `; edit the registry, not
the section.

`

const snippet = `## Architecture (arc)

The architecture registry is ` + "`" + Path + "`" + `; ` + "`" + ArchitectureFile + "`" + ` has the rendered view.

- Before feature work, run ` + "`arc brief <paths>`" + ` (or ` + "`arc brief`" + ` for everything) and follow the owning concept's rules.
- Extend the concept that owns the code; do not build a parallel version of something that exists.
- New concepts, tables, env vars and flags need a registry entry with a reason in the same change.
- Replacing something means deleting the old code in the same change, or adding a ` + "`removals`" + ` entry.
- Before creating files in a new directory, run ` + "`arc place <path>`" + `; unowned files fail ` + "`arc gate`" + `.
- After editing the registry, run ` + "`arc render`" + ` and ` + "`arc validate`" + `.
`

// Snippet returns the agent instruction block body.
func Snippet() string { return snippet }

// RenderArchitecture returns the generated markdown for ARCHITECTURE.md's
// arc block. Ordering follows the registry, so output is deterministic.
func (r *Registry) RenderArchitecture() string {
	var b strings.Builder
	b.WriteString("<!-- Generated by `arc render` from " + Path + ". Do not edit by hand. -->\n\n")
	b.WriteString("## Architecture registry\n\n")
	name := r.System.Name
	if name == "" {
		name = "System"
	}
	if s := oneLine(r.System.Summary); s != "" {
		fmt.Fprintf(&b, "**%s**: %s\n\n", name, s)
	} else {
		fmt.Fprintf(&b, "**%s**\n\n", name)
	}

	if len(r.NonGoals) > 0 {
		b.WriteString("### Non-goals\n\n")
		for _, n := range r.NonGoals {
			fmt.Fprintf(&b, "- **%s**: %s\n", n.ID, oneLine(n.Text))
		}
		b.WriteString("\n")
	}

	b.WriteString("### Concepts\n\n")
	if len(r.Concepts) == 0 {
		b.WriteString("None yet.\n\n")
	} else {
		b.WriteString("| Concept | Owns paths | Storage | Env | Summary |\n|---|---|---|---|---|\n")
		for _, c := range r.Concepts {
			id := c.ID
			if c.Name != "" && c.Name != c.ID {
				id += " (" + c.Name + ")"
			}
			if c.Draft {
				id += " *draft*"
			}
			summary := oneLine(c.Summary)
			if why := oneLine(c.Reason); why != "" {
				summary += " *Why:* " + why
			}
			row(&b, id, codeList(c.Paths), strings.Join(c.Storage, ", "),
				strings.Join(c.Env, ", "), summary)
		}
		b.WriteString("\n")
	}

	if len(r.Boundaries) > 0 {
		b.WriteString("### Boundaries\n\n")
		for _, x := range r.Boundaries {
			fmt.Fprintf(&b, "- **%s**: %s must not import %s.", x.ID, codeList(x.From), codeList(x.Deny))
			if reason := oneLine(x.Reason); reason != "" {
				b.WriteString(" " + reason)
			}
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	if len(r.Flags) > 0 {
		b.WriteString("### Flags\n\n| Flag | Concept | Purpose | Expires | Bead |\n|---|---|---|---|---|\n")
		for _, f := range r.Flags {
			row(&b, "`"+f.Name+"`", f.Concept, oneLine(f.Purpose), f.Expires, f.Bead)
		}
		b.WriteString("\n")
	}

	if len(r.Removals) > 0 {
		b.WriteString("### Scheduled removals\n\n| What | Replaced by | Remove by | Bead |\n|---|---|---|---|\n")
		for _, rm := range r.Removals {
			what := oneLine(rm.What)
			if what == "" {
				what = rm.ID
			}
			row(&b, what, rm.ReplacedBy, rm.RemoveBy, rm.Bead)
		}
		b.WriteString("\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

func row(b *strings.Builder, cells ...string) {
	for i, c := range cells {
		cells[i] = strings.ReplaceAll(c, "|", `\|`)
	}
	b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
}

func codeList(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = "`" + x + "`"
	}
	return strings.Join(q, ", ")
}

// oneLine collapses whitespace, including newlines, to single spaces.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// ReplaceBlock returns doc with the text between the arc markers replaced
// by body. Without markers the block is appended. Malformed markers are an
// error rather than a guess, so text outside them is never lost.
func ReplaceBlock(doc, body string) (string, error) {
	block := BeginMarker + "\n" + body + EndMarker
	begin := strings.Index(doc, BeginMarker)
	end := strings.Index(doc, EndMarker)
	switch {
	case begin < 0 && end < 0:
		if doc != "" {
			doc = strings.TrimRight(doc, "\n") + "\n\n"
		}
		return doc + block + "\n", nil
	case begin < 0 || end < begin ||
		strings.Count(doc, BeginMarker) > 1 || strings.Count(doc, EndMarker) > 1:
		return "", errors.New("malformed arc markers: need exactly one " + BeginMarker + " followed by one " + EndMarker)
	}
	return doc[:begin] + block + doc[end+len(EndMarker):], nil
}

// planned is one file render would write.
type planned struct {
	path    string // repo-relative
	current string
	exists  bool
	want    string
}

// plan computes the desired content of every file render manages.
func (r *Registry) plan(root string) ([]planned, error) {
	var out []planned
	add := func(rel, body, header string, create bool) error {
		data, err := os.ReadFile(filepath.Join(root, rel))
		exists := err == nil
		if err != nil && !errors.Is(err, os.ErrNotExist) {
			return err
		}
		if !exists && !create {
			return nil
		}
		doc := string(data)
		if !exists {
			doc = header
		}
		want, err := ReplaceBlock(doc, body)
		if err != nil {
			return fmt.Errorf("%s: %w", rel, err)
		}
		out = append(out, planned{path: rel, current: string(data), exists: exists, want: want})
		return nil
	}
	if err := add(ArchitectureFile, r.RenderArchitecture(), architectureHeader, true); err != nil {
		return nil, err
	}
	for i, f := range SnippetFiles {
		if err := add(f, snippet, "", i == 0); err != nil {
			return nil, err
		}
	}
	return out, nil
}

// Render writes ARCHITECTURE.md and the agent snippets under root and
// returns the repo-relative paths it changed.
func (r *Registry) Render(root string) ([]string, error) {
	files, err := r.plan(root)
	if err != nil {
		return nil, err
	}
	var changed []string
	for _, f := range files {
		if f.exists && f.current == f.want {
			continue
		}
		if err := os.WriteFile(filepath.Join(root, f.path), []byte(f.want), 0o644); err != nil {
			return changed, err
		}
		changed = append(changed, f.path)
	}
	return changed, nil
}

// Stale returns the existing files whose arc block differs from what
// Render would write (a missing ARCHITECTURE.md counts as stale). A missing
// AGENTS.md does not: the snippet is guidance, the registry view is not.
func (r *Registry) Stale(root string) ([]string, error) {
	files, err := r.plan(root)
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, f := range files {
		if f.current != f.want && (f.exists || f.path == ArchitectureFile) {
			stale = append(stale, f.path)
		}
	}
	return stale, nil
}

// IsStale reports whether Render would change any existing file.
func (r *Registry) IsStale(root string) (bool, error) {
	s, err := r.Stale(root)
	return len(s) > 0, err
}
